#!/usr/bin/env python3
"""Reproduce the immutable V1 anomaly input from reverse-QA evidence."""

from __future__ import annotations

import csv
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path


HERE = Path(__file__).resolve().parent
REVERSE = HERE.parent / "output" / "reverse_qa_20261012" / "05_candidates_gt30.json"
ROOT_CAUSE = HERE.parent / "root_cause_20261012" / "output" / "root_cause_sample_30_final.json"
OUT = HERE / "input"
CSV_PATH = OUT / "research_price_anomalies_v1.csv"
MANIFEST_PATH = OUT / "research_price_anomalies_v1_manifest.json"
VERSION = "corporate_action_reverse_qa_20261012+2429_control_v1"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    candidates = json.loads(REVERSE.read_text(encoding="utf-8"))
    final_sample = json.loads(ROOT_CAUSE.read_text(encoding="utf-8"))
    material = [row for row in candidates if abs(float(row["adjusted_return"])) > 0.50]
    if len(material) != 360 or len({row["ticker"] for row in material}) != 262:
        raise RuntimeError("reverse-QA material baseline does not reconcile to 360 transitions / 262 tickers")
    control = next(row for row in candidates if row["ticker"] == "2429" and row["date"] == "2024-07-02")
    control_evidence = next(row for row in final_sample if row["ticker"] == "2429" and row["quote_date"] == "2024-07-02")
    if control_evidence["classification"] != "CONFIRMED_ADJUSTMENT_ERROR":
        raise RuntimeError("2429 control is not authoritatively classified")

    rows = []
    for row in material:
        rows.append({
            "ticker": str(row["ticker"]), "prev_quote_date": row["prev_quote_date"],
            "quote_date": row["date"], "raw_return": row["raw_return"],
            "adjusted_return": row["adjusted_return"],
            "missing_market_sessions": row["missing_market_sessions"],
            "anomaly_reason": "MATERIAL_ADJUSTED_PRICE_DISCONTINUITY_GT_50PCT",
            "anomaly_source": "reverse_price_discontinuity_audit",
            "source_audit_version": VERSION, "is_material_gt50": True,
        })
    rows.append({
        "ticker": "2429", "prev_quote_date": control["prev_quote_date"],
        "quote_date": control["date"], "raw_return": control["raw_return"],
        "adjusted_return": control["adjusted_return"],
        "missing_market_sessions": control["missing_market_sessions"],
        "anomaly_reason": "CONFIRMED_PAID_RIGHTS_ADJUSTMENT_ERROR",
        "anomaly_source": "root_cause_20261012_twse_twt49u_detail",
        "source_audit_version": VERSION, "is_material_gt50": False,
    })
    rows.sort(key=lambda row: (row["ticker"], row["quote_date"], row["prev_quote_date"]))
    keys = {(row["ticker"], row["prev_quote_date"], row["quote_date"]) for row in rows}
    if len(rows) != 361 or len(keys) != 361:
        raise RuntimeError("V1 anomaly input must have 360 material transitions plus one distinct control")
    OUT.mkdir(parents=True, exist_ok=True)
    with CSV_PATH.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    manifest = {
        "schema_version": 1, "source_audit_version": VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": str(Path(__file__).relative_to(HERE.parents[2])),
        "sources": [
            {"path": str(REVERSE), "sha256": sha256(REVERSE)},
            {"path": str(ROOT_CAUSE), "sha256": sha256(ROOT_CAUSE)},
        ],
        "output": {"path": str(CSV_PATH), "sha256": sha256(CSV_PATH)},
        "transition_key": ["ticker", "prev_quote_date", "quote_date"],
        "material_rule": "abs(adjusted_return) > 0.50",
        "material_rows": 360, "material_tickers": 262,
        "additional_control_rows": 1, "total_rows": 361,
        "notes": [
            "An anomaly is a conservative research-quality flag, not an inferred corporate action.",
            "2429 2024-07-02 is outside the material population and remains separately identified.",
            "No adjustment factor is generated by this input.",
        ],
    }
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
